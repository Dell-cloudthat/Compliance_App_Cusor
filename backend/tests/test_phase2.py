# ── Test IDs ──────────────────────────────────────────────────────────────────

ORG_P2 = "org-phase2-test-001"
MSP_ID_P2 = "msp-phase2-test"

# User IDs for each role
UID_ADMIN  = "user-p2-admin"
UID_EXEC   = "user-p2-exec"
UID_ENG    = "user-p2-engineer"
UID_TECH   = "user-p2-msp-tech"   # MSP technician
UID_AUDIT  = "user-p2-auditor"
UID_NOBODY = "user-p2-nobody"     # valid JWT but no membership in ORG_P2


def _tok(
    *,
    user_id: str,
    org_id: str = ORG_P2,
    msp_id: str | None = None,
    email: str | None = None,
    name: str | None = None,
) -> str:
    claims: dict = {
        "sub": user_id,
        "email": email or f"{user_id}@example.com",
        "name": name or user_id,
        "org_id": org_id,
    }
    if msp_id is not None:
        claims["msp_id"] = msp_id
    return sign_dev_token(claims, expires_in=3600)


# Build tokens at module level (key is already generated by conftest)
ADMIN_TOKEN  = _tok(user_id=UID_ADMIN)
EXEC_TOKEN   = _tok(user_id=UID_EXEC)
ENG_TOKEN    = _tok(user_id=UID_ENG)
TECH_TOKEN   = _tok(user_id=UID_TECH, org_id="org-msp-internal-p2", msp_id=MSP_ID_P2)
AUDIT_TOKEN  = _tok(user_id=UID_AUDIT)
NOBODY_TOKEN = _tok(user_id=UID_NOBODY, org_id="org-p2-other")


