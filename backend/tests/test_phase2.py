def test_invite_and_revoke_member(client):
    """Admin invites a new user, then revokes the membership."""
    new_uid = "user-p2-invite-test"
    invite_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/members",
        json={"user_id": new_uid, "role": "auditor"},
        headers=_auth(ADMIN_TOKEN),
    )
    assert invite_resp.status_code == 201, f"Invite: {invite_resp.text}"
    assert invite_resp.json()["membership"]["role"] == "auditor"

    # Revoke
    revoke_resp = client.delete(
        f"/api/v1/securityos/organizations/{ORG_P2}/members/{new_uid}",
        headers=_auth(ADMIN_TOKEN),
    )
    assert revoke_resp.status_code == 204, f"Revoke: {revoke_resp.text}"

    # Gone from the list
    list_resp = client.get(
        f"/api/v1/securityos/organizations/{ORG_P2}/members",
        headers=_auth(ADMIN_TOKEN),
    )
    uids_in_org = [m["user_id"] for m in list_resp.json()["members"]]
    assert new_uid not in uids_in_org


