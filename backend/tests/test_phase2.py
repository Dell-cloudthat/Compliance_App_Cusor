"""
Phase 2 Acceptance Tests — RBAC via org_memberships

Tests the following acceptance criteria:

  - Authorization comes from org_memberships, not token org_id alone.
  - Client executive (role=executive) CAN create attestations → 201.
  - MSP technician (role=msp_technician) CANNOT create attestations → 403.
  - Permission matrix: every role × every protected endpoint.
  - Findings state machine: full lifecycle happy path.
  - Self-approval prohibition: same user submit + approve → 409.
  - Members API: invite, list, change role, revoke.

Security invariants preserved:
  - Actor fields always come from JWT, never from body.
  - Server sets all timestamps.
  - Deny by default: no membership → 403.
  - Cross-tenant access returns 404.
"""

import pytest
