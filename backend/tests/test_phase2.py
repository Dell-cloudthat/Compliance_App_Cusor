# ── Finding lifecycle — happy path ────────────────────────────────────────────

def test_finding_full_lifecycle(client):
    """
    Full finding lifecycle:
      engineer creates → engineer assigns → engineer starts → engineer submits
      → executive approves → closed
    """
    # 1. Create finding (engineer)
    create_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings",
        json={
            "title": "Missing MFA on admin accounts",
            "description": "Admin accounts do not enforce MFA.",
            "severity": "high",
            "control_ids": ["CTRL-P2-IAM-001"],
        },
        headers=_auth(ENG_TOKEN),
    )
    assert create_resp.status_code == 201, f"Create finding: {create_resp.text}"
    finding_id = create_resp.json()["finding"]["finding_id"]
    assert create_resp.json()["finding"]["state"] == "open"

    # 2. Assign (engineer assigns to themselves)
    assign_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "assign", "assigned_to_user_id": UID_ENG},
        headers=_auth(ENG_TOKEN),
    )
    assert assign_resp.status_code == 200, f"Assign: {assign_resp.text}"
    assert assign_resp.json()["finding"]["state"] == "assigned"

    # 3. Start (engineer)
    start_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "start"},
        headers=_auth(ENG_TOKEN),
    )
    assert start_resp.status_code == 200, f"Start: {start_resp.text}"
    assert start_resp.json()["finding"]["state"] == "in_progress"

    # 4. Submit for review (engineer)
    submit_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "submit", "note": "MFA enforced via Entra Conditional Access."},
        headers=_auth(ENG_TOKEN),
    )
    assert submit_resp.status_code == 200, f"Submit: {submit_resp.text}"
    assert submit_resp.json()["finding"]["state"] == "submitted_for_review"

    # 5. Approve (executive — NOT the same as the engineer who submitted)
    approve_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "approve", "note": "Verified MFA policy applied."},
        headers=_auth(EXEC_TOKEN),
    )
    assert approve_resp.status_code == 200, f"Approve: {approve_resp.text}"
    assert approve_resp.json()["finding"]["state"] == "closed"


# ── Self-approval prohibition ─────────────────────────────────────────────────

def test_self_approval_prohibited(client):
    """
    The same user who submitted a finding for review cannot approve/close it.
    Attempt → 409 Conflict.
    """
    # Create a finding
    create_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings",
        json={
            "title": "Self-approval test finding",
            "description": "Should not be self-approachable.",
            "severity": "medium",
            "control_ids": [],
        },
        headers=_auth(ADMIN_TOKEN),  # admin creates
    )
    assert create_resp.status_code == 201
    finding_id = create_resp.json()["finding"]["finding_id"]

    # Admin assigns
    client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "assign", "assigned_to_user_id": UID_ADMIN},
        headers=_auth(ADMIN_TOKEN),
    )

    # Admin starts
    client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "start"},
        headers=_auth(ADMIN_TOKEN),
    )

    # Admin submits (the same user who will try to approve)
    submit_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "submit", "note": "I fixed it."},
        headers=_auth(ADMIN_TOKEN),
    )
    assert submit_resp.status_code == 200

    # Same admin tries to approve — must be rejected
    approve_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "approve"},
        headers=_auth(ADMIN_TOKEN),
    )
    assert approve_resp.status_code == 409, (
        f"Expected 409 for self-approval, got {approve_resp.status_code}: {approve_resp.text}"
    )
    assert "self-approval" in approve_resp.json().get("detail", "").lower()


# ── Engineer cannot approve ───────────────────────────────────────────────────

def test_engineer_cannot_approve_finding(client):
    """Engineers lack finding.approve_close; approval attempt → 403."""
    create_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings",
        json={
            "title": "Engineer approve test",
            "description": "Test permission boundary.",
            "severity": "low",
            "control_ids": [],
        },
        headers=_auth(ENG_TOKEN),
    )
    assert create_resp.status_code == 201
    finding_id = create_resp.json()["finding"]["finding_id"]

    # Advance to submitted_for_review state via engineer path
    for action, body in [
        ("assign", {"action": "assign", "assigned_to_user_id": UID_ENG}),
        ("start", {"action": "start"}),
        ("submit", {"action": "submit"}),
    ]:
        r = client.post(
            f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
            json=body,
            headers=_auth(ENG_TOKEN),
        )
        assert r.status_code == 200, f"Step {action}: {r.text}"

    # Engineer tries to approve — should be 403
    approve_resp = client.post(
        f"/api/v1/securityos/organizations/{ORG_P2}/findings/{finding_id}/transition",
        json={"action": "approve"},
        headers=_auth(ENG_TOKEN),
    )
    assert approve_resp.status_code == 403, (
        f"Expected 403 for engineer approve, got {approve_resp.status_code}: {approve_resp.text}"
    )


